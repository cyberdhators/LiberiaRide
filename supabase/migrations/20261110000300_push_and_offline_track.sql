-- Driver at the pickup → passenger (who is often indoors with the screen off).
create or replace function public.tg_push_driver_arrived()
returns trigger
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
begin
  if new.status = 'DRIVER_ARRIVED' and old.status is distinct from 'DRIVER_ARRIVED' then
    perform public._push_enqueue(new.passenger_id, 'booking.driver_arrived', 'Your driver has arrived',
      coalesce((select 'Look for the ' || v.color || ' ' || v.make || ' ' || v.model || ', plate ' || v.plate_number
                  from public.vehicles v where v.id = new.vehicle_id), 'Your driver is at the pickup point.'),
      jsonb_build_object('booking_id', new.id), true, 900);
  end if;
  return null;
end;
$$;
create trigger bookings_push_driver_arrived after update of status on public.bookings
  for each row execute function public.tg_push_driver_arrived();

-- Safety net: retry anything still queued (e.g. the function was briefly down).
create or replace function public.push_retry()
returns void
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
begin
  if exists (select 1 from public.push_outbox where dispatched_at is null and created_at > now() - interval '1 hour') then
    perform public._push_kick();
  end if;
end;
$$;
select cron.schedule('liberia-ride-push-retry', '* * * * *', $$select public.push_retry()$$);

-- ---------------------------------------------------------------------
-- Offline GPS track upload (fixes buffered on the phone during a network gap)
-- ---------------------------------------------------------------------
create or replace function public.driver_upload_track(p_booking_id uuid, p_points jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_uid   uuid := public.require_active_user();
  v_b     public.bookings := public._lock_driver_booking(p_booking_id, v_uid);
  v_trip  public.trips;
  v_prev  public.trip_locations;
  v_pt    jsonb;
  v_at    timestamptz;
  v_acc   real;
  v_spd   real;
  v_loc   extensions.geography;
  v_max   integer := public.config_int('gps.max_accuracy_m');
  v_ok    integer := 0;
  v_bad   integer := 0;
begin
  if jsonb_typeof(p_points) is distinct from 'array' or jsonb_array_length(p_points) > 300 then
    raise exception 'send between 1 and 300 points at a time' using errcode = '22023';
  end if;
  if v_b.status <> 'IN_PROGRESS' then
    return jsonb_build_object('accepted', 0, 'rejected', jsonb_array_length(p_points), 'reason', 'trip_not_in_progress');
  end if;
  select * into v_trip from public.trips where booking_id = p_booking_id;

  for v_pt in select value from jsonb_array_elements(p_points) order by value->>'recorded_at' loop
    begin
      v_at  := (v_pt->>'recorded_at')::timestamptz;
      v_acc := (v_pt->>'accuracy_m')::real;
      v_spd := (v_pt->>'speed_mps')::real;
      v_loc := public.make_point((v_pt->>'lat')::double precision, (v_pt->>'lng')::double precision);
    exception when others then
      v_bad := v_bad + 1;
      continue;
    end;
    if v_at is null or v_acc is null or v_acc > v_max
       or v_at < v_trip.started_at or v_at > now() + interval '30 seconds'
       or exists (select 1 from public.trip_locations where trip_id = v_trip.id and recorded_at = v_at) then
      v_bad := v_bad + 1;
      continue;
    end if;
    -- Same plausibility rule as live updates: no jumps faster than 250 km/h.
    select * into v_prev from public.trip_locations
     where trip_id = v_trip.id and recorded_at < v_at order by recorded_at desc limit 1;
    if found and extensions.st_distance(v_prev.location, v_loc)
                 / greatest(extract(epoch from v_at - v_prev.recorded_at), 1) > 70 then
      v_bad := v_bad + 1;
      continue;
    end if;
    insert into public.trip_locations(trip_id, location, accuracy_m, speed_mps, recorded_at)
    values (v_trip.id, v_loc, v_acc, case when v_spd >= 0 then v_spd end, v_at);
    v_ok := v_ok + 1;
  end loop;
  return jsonb_build_object('accepted', v_ok, 'rejected', v_bad);
end;
$$;

-- Retention: delivered pushes after a day.
create or replace function public.run_retention()
returns void
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
begin
  delete from public.location_history where received_at < now() - interval '90 days';
  delete from public.trip_locations tl using public.trips t
   where t.id = tl.trip_id and t.ended_at < now() - interval '90 days';
  delete from public.realtime_events where created_at < now() - interval '30 days';
  delete from public.qls_lookup_cache where expires_at < now();
  delete from public.fare_estimates fe where fe.expires_at < now() - interval '7 days'
     and not exists (select 1 from public.bookings b where b.fare_estimate_id = fe.id);
  delete from public.push_outbox where created_at < now() - interval '1 day';
end;
$$;

