-- =====================================================================
-- LiberiaRide · 0028 · Web Push + offline GPS track upload
--
-- Push ("never miss a ride"):
--   offer / notification / driver-arrived → push_outbox (only for users who
--   enabled alerts) → pg_net kicks the `push-dispatch` Edge Function → it sends
--   an EMPTY Web Push (VAPID-signed, no payload encryption needed) → the
--   service worker fetches the text from /api/push/latest with the user's
--   session and shows it. A one-minute cron retries anything left unsent.
--   Secrets live in Supabase Vault: `push_invoke_key` (database → function)
--   and `push_vapid` (key pair, generated by the function on first run).
--   `push.dispatch_url` is per project and set at deploy time (DEPLOYMENT.md).
--
-- Offline track: drivers buffer GPS fixes while the network is down and
-- upload them with driver_upload_track, so billing sees the real route.
-- =====================================================================

create extension if not exists pg_net with schema extensions;

insert into public.configuration_settings(key, value, description, is_public) values
  ('push.dispatch_url',   '""', 'URL of the push-dispatch Edge Function (empty = push off)', false),
  ('push.vapid_subject',  '"mailto:support@liberiaride.app"', 'VAPID contact (mailto: or https:) sent to push services', false)
on conflict (key) do nothing;

do $$
begin
  if not exists (select 1 from vault.secrets where name = 'push_invoke_key') then
    perform vault.create_secret(encode(extensions.gen_random_bytes(32), 'hex'), 'push_invoke_key',
                                'Shared key: database → push-dispatch Edge Function');
  end if;
end $$;

-- ---------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------
create table public.push_subscriptions (
  id              uuid primary key default gen_random_uuid(),
  user_id         uuid not null references public.profiles(id) on delete cascade,
  endpoint        text not null unique check (char_length(endpoint) <= 1000),
  p256dh          text not null check (char_length(p256dh) between 20 and 200),
  auth_secret     text not null check (char_length(auth_secret) between 8 and 100),
  user_agent      text check (char_length(user_agent) <= 300),
  failures        smallint not null default 0,
  last_status     smallint,
  last_success_at timestamptz,
  created_at      timestamptz not null default now()
);
create index push_subscriptions_user_idx on public.push_subscriptions(user_id);
alter table public.push_subscriptions enable row level security;
grant select (id, user_id, user_agent, last_status, last_success_at, created_at) on public.push_subscriptions to authenticated;
create policy push_subscriptions_owner on public.push_subscriptions for select to authenticated
  using (user_id = (select auth.uid()));

create table public.push_outbox (
  id            bigint generated always as identity primary key,
  user_id       uuid not null references public.profiles(id) on delete cascade,
  kind          text not null,
  title         text not null,
  body          text,
  data          jsonb not null default '{}'::jsonb,
  urgent        boolean not null default false,
  ttl_seconds   integer not null default 300 check (ttl_seconds between 0 and 86400),
  created_at    timestamptz not null default now(),
  dispatched_at timestamptz,
  shown_at      timestamptz
);
create index push_outbox_pending_idx on public.push_outbox(id) where dispatched_at is null;
create index push_outbox_user_idx on public.push_outbox(user_id, created_at desc);
alter table public.push_outbox enable row level security;   -- no API access; RPCs only

-- ---------------------------------------------------------------------
-- Client RPCs (signed-in users)
-- ---------------------------------------------------------------------
-- Only real push services: the dispatcher POSTs to these URLs, so arbitrary hosts are refused.
create or replace function public.push_subscribe(p_endpoint text, p_p256dh text, p_auth text, p_user_agent text default null)
returns uuid
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_uid uuid := public.require_active_user();
  v_id  uuid;
begin
  if p_endpoint is null or p_endpoint !~ '^https://(fcm\.googleapis\.com|android\.googleapis\.com|updates\.push\.services\.mozilla\.com|push\.services\.mozilla\.com|[a-z0-9.-]+\.push\.apple\.com|[a-z0-9.-]+\.notify\.windows\.com)/' then
    raise exception 'unsupported push service' using errcode = '22023';
  end if;
  insert into public.push_subscriptions(user_id, endpoint, p256dh, auth_secret, user_agent)
  values (v_uid, p_endpoint, p_p256dh, p_auth, left(p_user_agent, 300))
  on conflict (endpoint) do update set user_id = excluded.user_id, p256dh = excluded.p256dh,
    auth_secret = excluded.auth_secret, user_agent = excluded.user_agent, failures = 0
  returning id into v_id;
  -- Keep the 10 most recent devices per user.
  delete from public.push_subscriptions where user_id = v_uid and id in (
    select id from public.push_subscriptions where user_id = v_uid order by created_at desc offset 10);
  return v_id;
end;
$$;

create or replace function public.push_unsubscribe(p_endpoint text)
returns void
language sql
security definer
set search_path = public, extensions, pg_temp
as $$
  delete from public.push_subscriptions where endpoint = p_endpoint and user_id = (select auth.uid());
$$;

create or replace function public.push_public_key()
returns text
language sql
stable
security definer
set search_path = public, extensions, pg_temp
as $$
  select (decrypted_secret::jsonb) ->> 'public_key' from vault.decrypted_secrets where name = 'push_vapid';
$$;

-- What the service worker shows: the caller's recent, unshown pushes (marked shown).
create or replace function public.push_take_recent()
returns table (id bigint, kind text, title text, body text, data jsonb, urgent boolean, created_at timestamptz)
language sql
security definer
set search_path = public, extensions, pg_temp
as $$
  with t as (
    select o.id from public.push_outbox o
     where o.user_id = (select auth.uid()) and o.shown_at is null
       and o.created_at > now() - make_interval(secs => o.ttl_seconds)
     order by o.id desc limit 3
  )
  update public.push_outbox o set shown_at = now() from t where o.id = t.id
  returning o.id, o.kind, o.title, o.body, o.data, o.urgent, o.created_at;
$$;

-- ---------------------------------------------------------------------
-- Dispatcher RPCs (service role only: the push-dispatch Edge Function)
-- ---------------------------------------------------------------------
create or replace function public.push_check_key(p_key text)
returns boolean
language sql
stable
security definer
set search_path = public, extensions, pg_temp
as $$
  select coalesce((select decrypted_secret = p_key from vault.decrypted_secrets where name = 'push_invoke_key'), false)
     and coalesce(length(p_key), 0) >= 32;
$$;

create or replace function public.push_vapid()
returns jsonb
language sql
stable
security definer
set search_path = public, extensions, pg_temp
as $$
  select (select decrypted_secret::jsonb from vault.decrypted_secrets where name = 'push_vapid')
         || jsonb_build_object('subject', public.config_text('push.vapid_subject'));
$$;

-- First writer wins; concurrent first runs all end up with the same stored pair.
create or replace function public.push_set_vapid(p_private_jwk jsonb, p_public_key text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
begin
  if not exists (select 1 from vault.secrets where name = 'push_vapid') then
    begin
      perform vault.create_secret(jsonb_build_object('private_jwk', p_private_jwk, 'public_key', p_public_key)::text,
                                  'push_vapid', 'Web Push VAPID key pair');
    exception when unique_violation then null;
    end;
  end if;
  return public.push_vapid();
end;
$$;

create or replace function public.push_claim_batch(p_limit integer default 100)
returns table (outbox_id bigint, subscription_id uuid, endpoint text, urgent boolean, ttl_seconds integer)
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
begin
  -- Too late to be useful (an offer that already expired): drop.
  update public.push_outbox o set dispatched_at = now()
   where o.dispatched_at is null and o.created_at + make_interval(secs => o.ttl_seconds) < now();

  return query
  with c as (
    select o.id from public.push_outbox o where o.dispatched_at is null
     order by o.id limit least(greatest(p_limit, 1), 500) for update skip locked
  ), u as (
    update public.push_outbox o set dispatched_at = now() from c where o.id = c.id
    returning o.id, o.user_id, o.urgent, o.ttl_seconds, o.created_at
  )
  select u.id, s.id, s.endpoint, u.urgent,
         greatest(0, u.ttl_seconds - extract(epoch from now() - u.created_at)::integer)
    from u join public.push_subscriptions s on s.user_id = u.user_id;
end;
$$;

create or replace function public.push_report(p_results jsonb)
returns void
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
begin
  -- 404/410: the browser unsubscribed or the subscription expired.
  delete from public.push_subscriptions s using jsonb_to_recordset(p_results) r(subscription_id uuid, status integer)
   where s.id = r.subscription_id and r.status in (404, 410);
  update public.push_subscriptions s
     set last_status = r.status,
         failures = case when r.status between 200 and 299 then 0 else s.failures + 1 end,
         last_success_at = case when r.status between 200 and 299 then now() else s.last_success_at end
    from jsonb_to_recordset(p_results) r(subscription_id uuid, status integer)
   where s.id = r.subscription_id;
  delete from public.push_subscriptions where failures >= 20;
end;
$$;

-- ---------------------------------------------------------------------
-- Enqueue + kick
-- ---------------------------------------------------------------------
create or replace function public._push_enqueue(
  p_user_id uuid, p_kind text, p_title text, p_body text, p_data jsonb, p_urgent boolean, p_ttl_seconds integer)
returns void
language sql
security definer
set search_path = public, extensions, pg_temp
as $$
  insert into public.push_outbox(user_id, kind, title, body, data, urgent, ttl_seconds)
  select p_user_id, p_kind, left(p_title, 120), left(p_body, 300), coalesce(p_data, '{}'::jsonb), p_urgent,
         least(greatest(coalesce(p_ttl_seconds, 300), 0), 86400)
   where exists (select 1 from public.push_subscriptions s where s.user_id = p_user_id);
$$;

create or replace function public._push_kick()
returns void
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_url text := nullif(btrim(coalesce(public.config_text('push.dispatch_url'), '')), '');
  v_key text;
begin
  if v_url is null then return; end if;
  select decrypted_secret into v_key from vault.decrypted_secrets where name = 'push_invoke_key';
  if v_key is null then return; end if;
  -- pg_net is asynchronous and transactional: the request is sent after commit.
  perform net.http_post(url := v_url, body := '{}'::jsonb,
                        headers := jsonb_build_object('Content-Type', 'application/json', 'x-push-key', v_key),
                        timeout_milliseconds := 10000);
exception when others then
  raise warning 'push kick failed: %', sqlerrm;
end;
$$;

create or replace function public.tg_push_outbox_kick()
returns trigger
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
begin
  perform public._push_kick();
  return null;
end;
$$;
create trigger push_outbox_kick after insert on public.push_outbox
  for each statement execute function public.tg_push_outbox_kick();

-- New ride offer → driver (urgent, lives as long as the offer).
create or replace function public.tg_push_offer()
returns trigger
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
begin
  if new.status = 'pending' then
    perform public._push_enqueue(new.driver_id, 'offer', 'New ride request',
      'Pickup: ' || left(coalesce(new.pickup_address, 'nearby'), 80) || ' · ' || new.currency::text || ' '
        || to_char(new.fare_minor / 100.0, 'FM999G999G990D00')
        || case when new.pickup_distance_m is not null then ' · ' || round(new.pickup_distance_m / 1000.0, 1) || ' km away' else '' end,
      jsonb_build_object('offer_id', new.id), true,
      greatest(1, extract(epoch from new.expires_at - now())::integer));
  end if;
  return null;
end;
$$;
create trigger booking_offers_push after insert on public.booking_offers
  for each row execute function public.tg_push_offer();

